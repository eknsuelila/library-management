-- =====================================================================================================
-- V1: initial schema for the Library Management System.
--
-- HOW FLYWAY WORKS
--   * At startup Flyway looks at the table "flyway_schema_history" to see which scripts already ran.
--   * Any script whose version (the "1" in V1__...) is newer is executed, in order, exactly once.
--   * NEVER edit a migration that has already run somewhere: Flyway stores a checksum and will refuse to
--     start. To change the schema, add a new file such as V2__add_fine_paid_column.sql.
--
-- PORTABILITY
--   This SQL runs unchanged on PostgreSQL (production) and on H2 started with MODE=PostgreSQL
--   (development and tests). That is why we stick to standard types and avoid vendor-only features
--   such as PostgreSQL partial indexes.
-- =====================================================================================================


-- -----------------------------------------------------------------------------------------------------
-- users: everyone who can log in, librarians and members alike.
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE users (
    -- "GENERATED BY DEFAULT AS IDENTITY" = auto-increment primary key (SQL standard, works on both DBs).
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    -- UNIQUE creates an index too, so looking a user up by email at login is fast.
    email         VARCHAR(255) NOT NULL UNIQUE,
    -- Only the BCrypt HASH is stored, never the plain-text password.
    password_hash VARCHAR(255) NOT NULL,
    -- Stored as text ('LIBRARIAN' / 'MEMBER') rather than a number so the data is readable and adding a
    -- role later can never shift the meaning of existing rows. The CHECK rejects typos at the DB level.
    role          VARCHAR(20)  NOT NULL DEFAULT 'MEMBER' CHECK (role IN ('LIBRARIAN', 'MEMBER')),
    created_at    TIMESTAMP    NOT NULL
);


-- -----------------------------------------------------------------------------------------------------
-- books: one row per TITLE. Physical copies are counted, not stored individually.
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE books (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ISBN-10 or ISBN-13, digits only. UNIQUE: the same edition cannot be catalogued twice.
    isbn             VARCHAR(13)   NOT NULL UNIQUE,
    title            VARCHAR(200)  NOT NULL,
    author           VARCHAR(150)  NOT NULL,
    genre            VARCHAR(50)   NOT NULL,
    published_year   INTEGER,
    -- total_copies: how many copies the library owns.
    -- available_copies: how many are on the shelf right now (total minus copies on loan).
    -- The CHECK constraints are a last line of defence: even if a bug slipped past the service layer,
    -- the database would refuse to store a negative stock or more available copies than owned.
    total_copies     INTEGER       NOT NULL CHECK (total_copies >= 0),
    available_copies INTEGER       NOT NULL CHECK (available_copies >= 0),
    description      VARCHAR(2000),
    cover_url        VARCHAR(500),
    -- Optimistic-locking counter maintained by Hibernate (@Version on Book.version).
    -- Every UPDATE runs "... SET version = version + 1 WHERE id = ? AND version = ?". If another
    -- transaction changed the row first, the WHERE matches 0 rows and Hibernate throws an exception
    -- instead of silently overwriting the other change (e.g. two members borrowing the last copy).
    version          BIGINT        NOT NULL DEFAULT 0,
    created_at       TIMESTAMP     NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    CONSTRAINT chk_books_available_le_total CHECK (available_copies <= total_copies)
);

-- Speeds up the genre filter on the catalog page and the "list genres" query.
CREATE INDEX idx_books_genre ON books (genre);


-- -----------------------------------------------------------------------------------------------------
-- loans: one row each time a member borrows a book. Rows are never deleted when a book is returned;
-- returned_date is filled in instead, which keeps the full borrowing history for statistics.
--
-- NOTE: there is deliberately NO status column. Whether a loan is ACTIVE, OVERDUE or RETURNED depends
-- on today's date, so it is computed from due_date/returned_date when needed (see Loan.statusOn).
-- A stored status would go stale every midnight unless a scheduled job kept rewriting it.
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE loans (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Foreign keys guarantee every loan points at an existing book and user.
    book_id       BIGINT        NOT NULL REFERENCES books (id),
    member_id     BIGINT        NOT NULL REFERENCES users (id),
    borrowed_date DATE          NOT NULL,
    due_date      DATE          NOT NULL,
    -- NULL while the book is still out.
    returned_date DATE,
    renew_count   INTEGER       NOT NULL DEFAULT 0,
    -- NUMERIC(8,2) = exact decimal with 2 places (money). Never use FLOAT/DOUBLE for money:
    -- binary floating point cannot represent 0.10 exactly and rounding errors accumulate.
    fine          NUMERIC(8, 2) NOT NULL DEFAULT 0,
    created_at    TIMESTAMP     NOT NULL
);

-- The business rules constantly ask "which loans of member X / book Y are still open?"
-- (returned_date IS NULL). Composite indexes on (member_id, returned_date) and (book_id, returned_date)
-- let the database answer those questions without scanning the whole table.
CREATE INDEX idx_loans_member_returned ON loans (member_id, returned_date);
CREATE INDEX idx_loans_book_returned   ON loans (book_id, returned_date);
-- Used by the "loans per month" chart and the default sort of the librarian's loan list.
CREATE INDEX idx_loans_borrowed_date   ON loans (borrowed_date);
