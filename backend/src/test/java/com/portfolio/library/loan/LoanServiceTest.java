package com.portfolio.library.loan;

import com.portfolio.library.book.Book;
import com.portfolio.library.book.BookRepository;
import com.portfolio.library.common.ConflictException;
import com.portfolio.library.common.ResourceNotFoundException;
import com.portfolio.library.loan.dto.BorrowRequest;
import com.portfolio.library.loan.dto.LoanResponse;
import com.portfolio.library.user.Role;
import com.portfolio.library.user.User;
import com.portfolio.library.user.UserRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.test.util.ReflectionTestUtils;

import java.math.BigDecimal;
import java.time.*;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

/**
 * UNIT tests for {@link LoanService}: every lending rule, in isolation.
 *
 * <ul>
 *   <li>No Spring context and no database: the repositories are Mockito MOCKS - fake objects whose answers we
 *       script with {@code when(...).thenReturn(...)} and whose calls we check with {@code verify(...)}.
 *       Unscripted methods return "empty" defaults (false, 0, null), which is why each test only stubs the
 *       one query it is about. Tests run in milliseconds.</li>
 *   <li>The {@link Clock} is FIXED to 2026-10-14, so "today", due dates, overdue checks and fines are
 *       deterministic no matter when the tests run. This is the payoff of injecting a Clock.</li>
 * </ul>
 *
 * Test names read as sentences: {@code methodUnderTest_expectedBehaviour_condition}.
 */
@ExtendWith(MockitoExtension.class)
class LoanServiceTest {

    private static final LocalDate TODAY = LocalDate.of(2026, 10, 14);
    private static final Clock FIXED_CLOCK = Clock.fixed(Instant.parse("2026-10-14T12:00:00Z"), ZoneOffset.UTC);

    @Mock private LoanRepository loans;
    @Mock private BookRepository books;
    @Mock private UserRepository users;

    private LoanService service;
    private User member;
    private User otherMember;
    private User librarian;
    private Book book;

    @BeforeEach
    void setUp() {
        service = new LoanService(loans, books, users, FIXED_CLOCK);
        member = user(1L, "Maya", Role.MEMBER);
        otherMember = user(2L, "Alex", Role.MEMBER);
        librarian = user(9L, "Lena", Role.LIBRARIAN);
        book = new Book("9780441172719", "Dune", "Frank Herbert", "Science Fiction", 2);
        // ids are normally generated by the database; set them by reflection for the test.
        ReflectionTestUtils.setField(book, "id", 100L);
    }

    // ---------------------------------------------------------------- borrowing

    @Test
    void borrow_createsLoanDueIn14Days_andTakesACopyOffTheShelf() {
        when(books.findById(100L)).thenReturn(Optional.of(book));
        // "Answer" with whatever was passed to save(), like a real repository would.
        when(loans.save(any(Loan.class))).thenAnswer(inv -> inv.getArgument(0));

        LoanResponse response = service.borrow(member, new BorrowRequest(100L, null));

        assertThat(response.borrowedDate()).isEqualTo(TODAY);
        assertThat(response.dueDate()).isEqualTo(TODAY.plusDays(14));
        assertThat(response.status()).isEqualTo(LoanStatus.ACTIVE);
        assertThat(response.memberId()).isEqualTo(1L);
        assertThat(book.getAvailableCopies()).isEqualTo(1);        // 2 -> 1
        verify(books).saveAndFlush(book);                           // flushed => @Version checked immediately
    }

    @Test
    void borrow_isRejected_whenNoCopiesAreAvailable() {
        Book lastCopyGone = new Book("9780201616224", "The Pragmatic Programmer", "Hunt", "Technology", 1);
        lastCopyGone.checkOutCopy();                                // 0 of 1 available
        when(books.findById(100L)).thenReturn(Optional.of(lastCopyGone));

        assertThatThrownBy(() -> service.borrow(member, new BorrowRequest(100L, null)))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("No copies");
        verify(loans, never()).save(any());
    }

    @Test
    void borrow_isRejected_whenMemberAlreadyHasThreeActiveLoans() {
        when(books.findById(100L)).thenReturn(Optional.of(book));
        when(loans.countByMemberIdAndReturnedDateIsNull(1L)).thenReturn(3L);

        assertThatThrownBy(() -> service.borrow(member, new BorrowRequest(100L, null)))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("at most 3");
    }

    @Test
    void borrow_isRejected_whenMemberAlreadyHasThisBook() {
        when(books.findById(100L)).thenReturn(Optional.of(book));
        when(loans.existsByMemberIdAndBookIdAndReturnedDateIsNull(1L, 100L)).thenReturn(true);

        assertThatThrownBy(() -> service.borrow(member, new BorrowRequest(100L, null)))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("already have a copy of \"Dune\"");
    }

    @Test
    void borrow_isRejected_whileMemberHasAnOverdueLoan() {
        when(books.findById(100L)).thenReturn(Optional.of(book));
        when(loans.existsByMemberIdAndReturnedDateIsNullAndDueDateBefore(1L, TODAY)).thenReturn(true);

        assertThatThrownBy(() -> service.borrow(member, new BorrowRequest(100L, null)))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("overdue");
    }

    @Test
    void borrow_memberCannotBorrowOnBehalfOfSomeoneElse() {
        assertThatThrownBy(() -> service.borrow(member, new BorrowRequest(100L, 2L)))
                .isInstanceOf(AccessDeniedException.class);
    }

    @Test
    void borrow_librarianLendsToTheGivenMember() {
        when(users.findById(2L)).thenReturn(Optional.of(otherMember));
        when(books.findById(100L)).thenReturn(Optional.of(book));
        when(loans.save(any(Loan.class))).thenAnswer(inv -> inv.getArgument(0));

        LoanResponse response = service.borrow(librarian, new BorrowRequest(100L, 2L));

        assertThat(response.memberId()).isEqualTo(2L);
        assertThat(response.memberName()).isEqualTo("Alex");
    }

    // ---------------------------------------------------------------- renewing

    @Test
    void renew_extendsDueDateBy14Days_onlyOnce() {
        Loan loan = loan(member, TODAY.minusDays(5));               // due in 9 days
        when(loans.findByIdAndMemberId(7L, 1L)).thenReturn(Optional.of(loan));

        LoanResponse renewed = service.renew(member, 7L);

        assertThat(renewed.dueDate()).isEqualTo(TODAY.plusDays(9 + 14));
        assertThat(renewed.renewCount()).isEqualTo(1);
        assertThat(renewed.canRenew()).isFalse();

        // Second attempt: rejected.
        assertThatThrownBy(() -> service.renew(member, 7L))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("already been renewed");
    }

    @Test
    void renew_isRejected_whenLoanIsOverdue() {
        Loan overdue = loan(member, TODAY.minusDays(20));           // was due 6 days ago
        when(loans.findByIdAndMemberId(7L, 1L)).thenReturn(Optional.of(overdue));

        assertThatThrownBy(() -> service.renew(member, 7L))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("Overdue loans cannot be renewed");
    }

    // ---------------------------------------------------------------- returning

    @Test
    void return_late_putsCopyBack_andCharges25CentsPerDay() {
        book.checkOutCopy();                                        // 1 of 2 on the shelf while on loan
        Loan loan = loan(member, TODAY.minusDays(18));              // due 4 days ago
        when(loans.findByIdAndMemberId(7L, 1L)).thenReturn(Optional.of(loan));

        LoanResponse returned = service.returnLoan(member, 7L);

        assertThat(returned.status()).isEqualTo(LoanStatus.RETURNED);
        assertThat(returned.returnedDate()).isEqualTo(TODAY);
        assertThat(returned.fine()).isEqualByComparingTo(new BigDecimal("1.00"));   // 4 days x $0.25
        assertThat(book.getAvailableCopies()).isEqualTo(2);
    }

    @Test
    void return_onTime_hasNoFine() {
        Loan loan = loan(member, TODAY.minusDays(14));              // due today => still on time
        when(loans.findByIdAndMemberId(7L, 1L)).thenReturn(Optional.of(loan));

        assertThat(service.returnLoan(member, 7L).fine()).isEqualByComparingTo(BigDecimal.ZERO);
    }

    @Test
    void return_isRejected_whenAlreadyReturned() {
        Loan loan = loan(member, TODAY.minusDays(3));
        loan.markReturned(TODAY.minusDays(1));
        when(loans.findByIdAndMemberId(7L, 1L)).thenReturn(Optional.of(loan));

        assertThatThrownBy(() -> service.returnLoan(member, 7L))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("already been returned");
    }

    @Test
    void return_memberCannotTouchAnotherMembersLoan() {
        // The member-scoped query finds nothing for someone else's loan id => 404, nothing is changed.
        when(loans.findByIdAndMemberId(7L, 1L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.returnLoan(member, 7L))
                .isInstanceOf(ResourceNotFoundException.class);
        verify(books, never()).saveAndFlush(any());
    }

    @Test
    void return_librarianCanReturnAnyLoan() {
        Loan loan = loan(otherMember, TODAY.minusDays(2));
        when(loans.findById(7L)).thenReturn(Optional.of(loan));

        assertThat(service.returnLoan(librarian, 7L).status()).isEqualTo(LoanStatus.RETURNED);
        verify(loans, never()).findByIdAndMemberId(any(), any());
    }

    // ---------------------------------------------------------------- helpers

    private static User user(long id, String name, Role role) {
        User u = new User(name, name.toLowerCase() + "@example.com", "hash", role);
        ReflectionTestUtils.setField(u, "id", id);
        return u;
    }

    private Loan loan(User who, LocalDate borrowed) {
        Loan loan = new Loan(book, who, borrowed);
        ReflectionTestUtils.setField(loan, "id", 7L);
        return loan;
    }
}
